def ensure_curriculum(db: Session, student: Student) -> int:
    """Досоздаёт недостающие предметы, темы и подтемы. Ничего не удаляет и не меняет.
    Совпадение по названию. Можно вызывать сколько угодно раз. Возвращает число новых подтем."""
    added = 0
    subjects = {s.name: s for s in db.query(Subject).filter_by(student_id=student.id)}
    for subject_name, topics in CURRICULUM.items():
        subject = subjects.get(subject_name)
        if subject is None:
            subject = Subject(student_id=student.id, name=subject_name)
            db.add(subject)
            db.flush()
            subjects[subject_name] = subject
        have_topics = {t.name: t for t in db.query(Topic).filter_by(subject_id=subject.id)}
        for topic_name, items in topics.items():
            topic = have_topics.get(topic_name)
            if topic is None:
                topic = Topic(subject_id=subject.id, name=topic_name)
                db.add(topic)
                db.flush()
                have_topics[topic_name] = topic
            have_subs = {st.name for st in db.query(Subtopic).filter_by(topic_id=topic.id)}
            for name, desc, *rest in items:
                if name in have_subs:
                    continue
                st = Subtopic(topic_id=topic.id, name=name, description=desc, key=rest[0] if rest else "")
                db.add(st)
                db.flush()
                if not st.key:
                    st.key = f"custom_{st.id}"
                db.add(SubtopicProgress(student_id=student.id, subtopic_id=st.id, mastery=0.5, tasks_done=0))
                added += 1
    db.commit()
    return added