def main() -> None:
    user = sys.argv[1] if len(sys.argv) > 1 else "alex"
    pwd = sys.argv[2] if len(sys.argv) > 2 else "demo12345"
    with httpx.Client(base_url=BASE, timeout=30) as c:
        r = c.post("/api/auth/login", json={"username": user, "password": pwd})
        r.raise_for_status()
        c.headers["Authorization"] = f"Bearer {r.json()['access_token']}"

        def tree() -> dict:
            return {s["name"]: s for s in c.get("/api/subjects").json()}

        added = 0
        for subject, topics in CURRICULUM.items():
            subs = tree()
            if subject not in subs:
                c.post("/api/subjects", json={"name": subject}).raise_for_status()
                subs = tree()
                added += 1
            sid = subs[subject]["id"]
            for topic, subtopics in topics.items():
                have = {t["name"]: t for t in subs[subject]["topics"]}
                if topic not in have:
                    c.post(f"/api/subjects/{sid}/topics", json={"name": topic}).raise_for_status()
                    subs = tree()
                    have = {t["name"]: t for t in subs[subject]["topics"]}
                tid = have[topic]["id"]
                known = {s["name"] for s in have[topic]["subtopics"]}
                for name, desc in subtopics:
                    if name not in known:
                        c.post(f"/api/topics/{tid}/subtopics",
                               json={"name": name, "description": desc}).raise_for_status()
        print(f"Готово. Новых предметов: {added}. Всего предметов: {len(tree())}")


if __name__ == "__main__":
    main()